const groups = {};
ROUTES.forEach((r) => (groups[r[2]] ||= []).push(r));
const sections = Object.entries(groups).map(([tag, routes]) => {
  const rows = routes.map(([m, p, , summary, access, opts = {}]) => {
    const extra = [opts.body && 'JSON body', opts.query && 'query params', opts.multipart && 'multipart', opts.csv && 'CSV'].filter(Boolean).join(', ');
    return `| \`${m.toUpperCase()}\` | \`${p}\` | ${ACCESS[access]} | ${summary}${extra ? ` (${extra})` : ''} |`;
  });
  return `### ${tag}\n\n| Method | Path | Access | Description |\n|---|---|---|---|\n${rows.join('\n')}\n`;
});

const out = path.join(root, 'docs', 'API.md');
fs.writeFileSync(out, `${intro}\n${sections.join('\n')}\n_Total: ${ROUTES.length} endpoints._\n`);
