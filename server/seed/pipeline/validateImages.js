// Step 3 - validate every product image URL, drop failures, write the curated seed files + report.
// Input:  raw/products.cleaned.json (or data/products.json when re-validating the curated set)
// Output: data/products.json, data/reviews.json, docs/IMAGE_REPORT.md
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { DATA_DIR, DOCS_DIR, RAW_DIR } from './config.js';

const MIN_BYTES = 5 * 1024; // smaller files are placeholders/thumbnails
const CONCURRENCY = 12;
const TIMEOUT_MS = 15000;

/** HTTP 200 + image/* content type + minimum size. Uses HEAD, falls back to a ranged GET. */
export async function checkImage(url) {
  const attempt = async (method) => {
    const ctrl = new AbortController();
    const timer = setTimeout(() => ctrl.abort(), TIMEOUT_MS);
    try {
      const res = await fetch(url, { method, redirect: 'follow', signal: ctrl.signal, headers: method === 'GET' ? { Range: 'bytes=0-65535' } : {} });
      const type = res.headers.get('content-type') || '';
      let size = Number(res.headers.get('content-length') || 0);
      const range = res.headers.get('content-range');
      if (range?.includes('/')) size = Number(range.split('/')[1]) || size;
      if (method === 'GET' && !size) size = (await res.arrayBuffer()).byteLength;
      else if (method === 'GET') await res.body?.cancel();
      return { status: res.status, type, size };
    } finally {
      clearTimeout(timer);
    }
  };
  try {
    let r = await attempt('HEAD');
    if (r.status !== 200 || !r.size) r = await attempt('GET');
    const okStatus = r.status === 200 || r.status === 206;
    if (!okStatus) return { ok: false, reason: `HTTP ${r.status}` };
    if (!r.type.startsWith('image/')) return { ok: false, reason: `content-type ${r.type || 'missing'}` };
    if (r.size < MIN_BYTES) return { ok: false, reason: `too small (${r.size} B)` };
    return { ok: true, type: r.type, size: r.size };
  } catch (err) {
    return { ok: false, reason: err.name === 'AbortError' ? 'timeout' : err.message };
  }
}

async function pool(items, worker) {
  const results = new Array(items.length);
  let i = 0;
  await Promise.all(
    Array.from({ length: CONCURRENCY }, async () => {
      while (i < items.length) {
        const idx = i++;
        results[idx] = await worker(items[idx], idx);
      }
    }),
  );
  return results;
}

function writeReport({ products, dropped, failures, checked, passed, startedAt }) {
  const byCat = {};
  products.forEach((p) => {
    byCat[p.category] ||= { products: 0, images: 0 };
    byCat[p.category].products += 1;
    byCat[p.category].images += p.images.length;
  });
  const lines = [
    '# Image Integrity Report',
    '',
    `Generated by \`npm run images:validate\` on ${new Date().toISOString()} (run took ${Math.round((Date.now() - startedAt) / 1000)} s).`,
    '',
    '## Method',
    '',
    '- Every image comes from the **same dataset record** as the product title, brand, specifications and reviews (Amazon Reviews 2023, `images[].hi_res` or `images[].large`), so each image shows that exact product. No random, stock, AI-generated or cross-product images are used.',
    `- Each URL is requested (HEAD, falling back to a ranged GET) and must return **HTTP 200**, a **\`image/*\` content type** and be at least **${MIN_BYTES / 1024} KB**.`,
    '- Failing images are removed; products left with zero valid images are dropped from the catalogue.',
    '- Licence: dataset image URLs point to the Amazon CDN and are used for **local / educational capstone use only**. Before any public deployment set `IMAGE_SOURCE=licensed` and supply licensed images (Wikimedia Commons, Unsplash, Pexels) in `server/seed/data/licensed-images.json` (see docs/DATASETS.md).',
    '',
    '## Summary',
    '',
    '| Metric | Value |',
    '|---|---|',
    `| Image URLs checked | ${checked} |`,
    `| Passed | ${passed} |`,
    `| Failed (removed) | ${checked - passed} |`,
    `| Products kept | ${products.length} |`,
    `| Products dropped (no valid image) | ${dropped.length} |`,
    '',
    '## Per category',
    '',
    '| Category | Products | Valid images | Images / product |',
    '|---|---|---|---|',
    ...Object.entries(byCat).map(([c, v]) => `| ${c} | ${v.products} | ${v.images} | ${(v.images / v.products).toFixed(1)} |`),
    '',
    '## Failures',
    '',
    failures.length ? '| Product | URL | Reason |\n|---|---|---|' : 'None - every image URL passed.',
    ...failures.slice(0, 200).map((f) => `| ${f.product.replace(/\|/g, '/')} | ${f.url} | ${f.reason} |`),
    '',
    dropped.length ? `Dropped products: ${dropped.map((d) => d.replace(/\|/g, '/')).join('; ')}` : '',
    '',
  ];
  fs.mkdirSync(DOCS_DIR, { recursive: true });
  fs.writeFileSync(path.join(DOCS_DIR, 'IMAGE_REPORT.md'), lines.join('\n'));
}

export async function validateImages({ log = console.log, input } = {}) {
  const startedAt = Date.now();
  const cleanedPath = path.join(RAW_DIR, 'products.cleaned.json');
  const curatedPath = path.join(DATA_DIR, 'products.json');
  const source = input || (fs.existsSync(cleanedPath) ? cleanedPath : curatedPath);
  const products = JSON.parse(fs.readFileSync(source, 'utf8'));
  let reviewsById = {};
  if (source === curatedPath && fs.existsSync(path.join(DATA_DIR, 'reviews.json'))) {
    reviewsById = JSON.parse(fs.readFileSync(path.join(DATA_DIR, 'reviews.json'), 'utf8'));
  }
  const jobs = products.flatMap((p, pi) => p.images.map((img) => ({ pi, url: img.url, product: p.name })));
  log(`[images] Checking ${jobs.length} image URLs for ${products.length} products (from ${path.relative(process.cwd(), source)})...`);
  let done = 0;
  const results = await pool(jobs, async (job) => {
    const r = await checkImage(job.url);
    done += 1;
    if (done % 100 === 0) log(`[images] ${done}/${jobs.length} checked`);
    return { ...job, ...r };
  });

  const failures = results.filter((r) => !r.ok);
  const okUrls = new Set(results.filter((r) => r.ok).map((r) => r.url));
  const kept = [];
  const dropped = [];
  for (const p of products) {
    const images = p.images.filter((img) => okUrls.has(img.url));
    if (!images.length) {
      dropped.push(p.name);
      continue;
    }
    kept.push({ ...p, images });
  }

  // Split reviews into their own file (keyed by dataset id) to keep products.json readable.
  const reviews = { ...reviewsById };
  const productsOut = kept.map(({ reviews: r, ...p }) => {
    if (r) reviews[p.source.sourceId] = r;
    return p;
  });
  fs.writeFileSync(curatedPath, `${JSON.stringify(productsOut, null, 1)}\n`);
  fs.writeFileSync(path.join(DATA_DIR, 'reviews.json'), `${JSON.stringify(reviews, null, 1)}\n`);
  const passed = results.length - failures.length;
  writeReport({ products: productsOut, dropped, failures, checked: jobs.length, passed, startedAt });
  log(`[images] ${passed}/${jobs.length} images passed; ${productsOut.length} products kept, ${dropped.length} dropped.`);
  log('[images] Wrote server/seed/data/products.json, server/seed/data/reviews.json and docs/IMAGE_REPORT.md');
  return { products: productsOut, failures, dropped };
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  validateImages().catch((err) => {
    console.error('[images] Failed:', err.message);
    process.exit(1);
  });
}
